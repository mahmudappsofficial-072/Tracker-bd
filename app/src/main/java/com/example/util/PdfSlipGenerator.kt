package com.example.util

import android.content.ContentValues
import android.content.Context
import android.content.Intent
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.net.Uri
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import android.text.Layout
import android.text.StaticLayout
import android.text.TextPaint
import android.text.TextUtils
import android.util.Log
import android.widget.Toast
import com.example.data.model.UserProfile
import com.example.ui.viewmodel.MonthlySummaryState
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream

object PdfSlipGenerator {

    suspend fun generateAndDownloadPdf(
        context: Context,
        profile: UserProfile,
        summary: MonthlySummaryState,
        selectedMonth: String,
        isBn: Boolean
    ): Uri? {
        var savedUri: Uri? = null
        var fileName = "Salary_Slip_$selectedMonth.pdf"
        var errorMessage: String? = null

        withContext(Dispatchers.IO) {
            val pdfDocument = PdfDocument()
            try {
                val pageWidth = 595 // A4 standard width in points
                val pageHeight = 842 // A4 standard height in points
                var pageNumber = 1
                var page = pdfDocument.startPage(
                    PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
                )
                var canvas = page.canvas

                val paint = Paint().apply {
                    isAntiAlias = true
                }
                val textPaint = TextPaint(paint)

                fun drawShapedText(
                    c: Canvas,
                    text: String,
                    x: Float,
                    baselineY: Float,
                    maxWidth: Float,
                    align: Layout.Alignment = Layout.Alignment.ALIGN_NORMAL
                ) {
                    if (text.isEmpty()) return
                    textPaint.set(paint)
                    textPaint.textAlign = Paint.Align.LEFT
                    val safeWidth = maxWidth.coerceAtLeast(24f).toInt()
                    val ellipsized = TextUtils.ellipsize(
                        text,
                        textPaint,
                        safeWidth.toFloat(),
                        TextUtils.TruncateAt.END
                    )
                    val layout = StaticLayout.Builder.obtain(
                        ellipsized,
                        0,
                        ellipsized.length,
                        textPaint,
                        safeWidth
                    )
                        .setAlignment(align)
                        .setLineSpacing(0f, 1f)
                        .setIncludePad(false)
                        .setMaxLines(1)
                        .setEllipsize(TextUtils.TruncateAt.END)
                        .build()

                    val drawX = when (align) {
                        Layout.Alignment.ALIGN_OPPOSITE -> x - safeWidth
                        Layout.Alignment.ALIGN_CENTER -> x - (safeWidth / 2f)
                        else -> x
                    }
                    val firstLineBaseline = layout.getLineBaseline(0).toFloat()
                    c.save()
                    c.translate(drawX, baselineY - firstLineBaseline)
                    layout.draw(c)
                    c.restore()
                }

                fun drawFooter(c: Canvas) {
                    val savedColor = paint.color
                    val savedSize = paint.textSize
                    val savedTypeface = paint.typeface
                    paint.color = Color.rgb(100, 116, 139)
                    paint.textSize = 9f
                    paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                    drawShapedText(
                        c = c,
                        text = if (isBn) "ওভারটাইম ট্র্যাকার বিডি দ্বারা প্রস্তুতকৃত" else "Generated by Overtime Tracker BD",
                        x = pageWidth / 2f,
                        baselineY = pageHeight - 36f,
                        maxWidth = pageWidth - 88f,
                        align = Layout.Alignment.ALIGN_CENTER
                    )
                    paint.color = savedColor
                    paint.textSize = savedSize
                    paint.typeface = savedTypeface
                }

                // Background card
                paint.color = Color.rgb(248, 250, 252)
                canvas.drawRect(24f, 24f, pageWidth - 24f, pageHeight - 24f, paint)

                // Header Background
                paint.color = Color.rgb(5, 150, 105) // Brand Primary
                canvas.drawRect(24f, 24f, pageWidth - 24f, 110f, paint)

                // Company Name
                paint.color = Color.WHITE
                paint.textSize = 20f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                val company = if (summary.companyName.isNotBlank()) summary.companyName
                else if (profile.companyName.isNotBlank()) profile.companyName
                else "Garments & Factory Ltd."
                drawShapedText(canvas, company, 44f, 60f, pageWidth - 156f)

                // Title
                paint.textSize = 12f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                val headerSubtitle = if (isBn) "মাসিক বেতন ও ওভারটাইম স্লিপ • $selectedMonth"
                else "Monthly Salary & Overtime Pay Slip • $selectedMonth"
                drawShapedText(canvas, headerSubtitle, 44f, 85f, pageWidth - 156f)

                // Brand Logo on top-right of PDF Header (recycled safely)
                var logoBmp: Bitmap? = null
                var scaledLogo: Bitmap? = null
                try {
                    logoBmp = BitmapFactory.decodeResource(context.resources, com.example.R.drawable.ic_app_logo)
                    if (logoBmp != null) {
                        scaledLogo = Bitmap.createScaledBitmap(logoBmp, 60, 60, true)
                        canvas.drawBitmap(scaledLogo, pageWidth - 96f, 37f, paint)
                    }
                } catch (e: Exception) {
                    Log.w("PdfSlipGenerator", "Failed to draw PDF header logo: ${e.message}")
                } finally {
                    if (scaledLogo != null && !scaledLogo.isRecycled) {
                        scaledLogo.recycle()
                    }
                    if (logoBmp != null && logoBmp !== scaledLogo && !logoBmp.isRecycled) {
                        logoBmp.recycle()
                    }
                }

                var y = 140f

                fun ensureSpace(neededHeight: Float) {
                    if (y + neededHeight > pageHeight - 60f) {
                        drawFooter(canvas)
                        pdfDocument.finishPage(page)
                        pageNumber++
                        page = pdfDocument.startPage(
                            PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
                        )
                        canvas = page.canvas
                        paint.color = Color.rgb(248, 250, 252)
                        paint.style = Paint.Style.FILL
                        canvas.drawRect(24f, 24f, pageWidth - 24f, pageHeight - 24f, paint)
                        y = 56f
                    }
                }

                // Employee Meta Box
                paint.color = Color.rgb(255, 255, 255)
                canvas.drawRect(44f, y - 16f, pageWidth - 44f, y + 60f, paint)

                val displayUserName = if (summary.userName.isNotBlank()) summary.userName else profile.userName
                val displayDesignation = if (summary.designation.isNotBlank()) summary.designation else profile.designation
                val displayGrade = if (summary.grade.isNotBlank()) summary.grade else profile.grade
                val displayWorkerId = if (summary.workerId.isNotBlank()) summary.workerId else profile.workerId

                val leftColX = 56f
                val rightColX = 312f
                val leftMaxWidth = rightColX - leftColX - 12f
                val rightMaxWidth = (pageWidth - 56f) - rightColX

                paint.color = Color.rgb(30, 41, 59)
                paint.textSize = 12f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                val workerNameText = if (isBn) "কর্মী নাম: $displayUserName" else "Worker Name: $displayUserName"
                drawShapedText(canvas, workerNameText, leftColX, y + 8f, leftMaxWidth)
                val formattedGrade = formatDisplayGrade(displayGrade, isBn)
                val designationLine = if (formattedGrade.isNotBlank()) {
                    if (isBn) "পদবি: $displayDesignation ($formattedGrade)" else "Designation: $displayDesignation ($formattedGrade)"
                } else {
                    if (isBn) "পদবি: $displayDesignation" else "Designation: $displayDesignation"
                }
                drawShapedText(canvas, designationLine, rightColX, y + 8f, rightMaxWidth)

                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                val workerIdText = if (isBn) "কার্ড / আইডি নং: $displayWorkerId" else "Card / ID No: $displayWorkerId"
                drawShapedText(canvas, workerIdText, leftColX, y + 36f, leftMaxWidth)
                val totalDays = summary.regularDutyDays + summary.dayShiftDays + summary.nightShiftDays
                val dutyLine = if (isBn) "মোট ডিউটি দিন: $totalDays দিন | নাইট: ${summary.nightShiftDays} দিন"
                else "Total Duty: $totalDays days | Night: ${summary.nightShiftDays} days"
                drawShapedText(canvas, dutyLine, rightColX, y + 36f, rightMaxWidth)

                y += 90f

                // Section: Attendance Summary
                ensureSpace(70f)
                paint.color = Color.rgb(5, 150, 105)
                paint.textSize = 13f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                drawShapedText(
                    canvas,
                    if (isBn) "হাজিরা ও শিফট বিবরণ:" else "Attendance & Shift Summary:",
                    44f,
                    y,
                    pageWidth - 88f
                )
                y += 20f

                paint.color = Color.rgb(71, 85, 105)
                paint.textSize = 11f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                val weeklyAndHolidays = summary.weeklyOffDays + summary.holidayDutyDays
                val leaveStatusText = if (summary.isBonusCancelledDueToLeave) {
                    if (isBn) " (হাজিরা বোনাস বাতিল)" else " (Bonus Cancelled)"
                } else ""
                val weeklyLine = if (isBn) "সাপ্তাহিক ও সরকারি ছুটি: $weeklyAndHolidays দিন" else "Weekly Off & Holiday: $weeklyAndHolidays days"
                val leaveLine = if (isBn) "সাময়িক ছুটি: ${summary.leaveDays} দিন$leaveStatusText" else "Leave: ${summary.leaveDays} days$leaveStatusText"
                drawShapedText(canvas, weeklyLine, leftColX, y, leftMaxWidth)
                drawShapedText(canvas, leaveLine, rightColX, y, rightMaxWidth)
                y += 18f

                val bonusStatusText = if (summary.attendanceBonus > 0) {
                    if (isBn) "(হাজিরা বোনাস অর্জিত)" else "(Attendance Bonus Earned)"
                } else if (summary.isBonusCancelledDueToAbsent) {
                    if (isBn) "(হাজিরা বোনাস কর্তন)" else "(Attendance Bonus Deducted)"
                } else {
                    ""
                }
                val absentLine = if (isBn) "অনুপস্থিত: ${summary.absentDays} দিন $bonusStatusText" else "Absent: ${summary.absentDays} days $bonusStatusText"
                drawShapedText(canvas, absentLine, leftColX, y, pageWidth - 112f)
                y += 20f

                // Divider
                paint.color = Color.rgb(226, 232, 240)
                paint.strokeWidth = 1f
                canvas.drawLine(44f, y, pageWidth - 44f, y, paint)
                y += 24f

                // Section: Basic & Allowances
                ensureSpace(45f)
                paint.color = Color.rgb(5, 150, 105)
                paint.textSize = 13f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                val sectionTitle = if (summary.isCustomSalary) {
                    if (isBn) "মোট বেতন ও ভাতাসমূহ:" else "Total Salary & Allowances:"
                } else {
                    if (isBn) "মূল বেতন ও নির্ধারিত ভাতাসমূহ:" else "Basic Salary & Fixed Allowances:"
                }
                drawShapedText(canvas, sectionTitle, 44f, y, pageWidth - 88f)
                y += 20f

                fun drawPdfRow(label: String, amount: Double, isBold: Boolean = false, isDeduction: Boolean = false) {
                    ensureSpace(22f)
                    paint.color = if (isDeduction) Color.rgb(220, 38, 38) else if (isBold) Color.rgb(15, 23, 42) else Color.rgb(71, 85, 105)
                    paint.textSize = 11f
                    paint.typeface = if (isBold || isDeduction) Typeface.create(Typeface.DEFAULT, Typeface.BOLD) else Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                    val valStr = if (isDeduction) {
                        String.format(java.util.Locale.US, "- Tk %.2f", kotlin.math.abs(amount))
                    } else {
                        String.format(java.util.Locale.US, "Tk %.2f", amount)
                    }
                    val valWidth = paint.measureText(valStr)
                    val maxLabelWidth = (pageWidth - 112f) - valWidth - 16f
                    drawShapedText(canvas, label, 56f, y, maxLabelWidth)
                    drawShapedText(
                        c = canvas,
                        text = valStr,
                        x = pageWidth - 56f,
                        baselineY = y,
                        maxWidth = valWidth + 24f,
                        align = Layout.Alignment.ALIGN_OPPOSITE
                    )
                    y += 18f
                }

                if (summary.isCustomSalary) {
                    drawPdfRow(if (isBn) "মোট বেতন" else "Total Salary", summary.basicSalary)
                } else {
                    val autoAllowances = if (summary.basicSalary > 0.0) {
                        LaborLawCalculator.calculateAutoAllowances(summary.basicSalary)
                    } else null

                    val effHouseRent = if (summary.houseRent > 0.0) summary.houseRent else (autoAllowances?.houseRent ?: profile.houseRent)
                    val effMedical = if (summary.medicalAllowance > 0.0) summary.medicalAllowance else (autoAllowances?.medicalAllowance ?: profile.medicalAllowance)
                    val effConveyance = if (summary.conveyanceAllowance > 0.0) summary.conveyanceAllowance else (autoAllowances?.conveyanceAllowance ?: profile.conveyanceAllowance)
                    val effFood = if (summary.foodAllowance > 0.0) summary.foodAllowance else (autoAllowances?.foodAllowance ?: profile.foodAllowance)

                    drawPdfRow(if (isBn) "মূল বেতন" else "Basic Salary", summary.basicSalary)
                    drawPdfRow(if (isBn) "বাড়িভাড়া ভাতা (৫০%)" else "House Rent Allowance (50%)", effHouseRent)
                    drawPdfRow(if (isBn) "চিকিৎসা ভাতা" else "Medical Allowance", effMedical)
                    drawPdfRow(if (isBn) "যাতায়াত ভাতা" else "Conveyance Allowance", effConveyance)
                    drawPdfRow(if (isBn) "খাদ্য ভাতা" else "Food Allowance", effFood)
                }
                val attendanceLabel = if (summary.attendanceBonus > 0) {
                    if (summary.absentDays > 0) {
                        if (isBn) "হাজিরা বোনাস (${summary.absentDays} দিন অনুপস্থিতি অনুমোদিত)" else "Attendance Bonus (${summary.absentDays} absent days allowed)"
                    } else {
                        if (isBn) "হাজিরা বোনাস (নিয়মিত উপস্থিতি)" else "Attendance Bonus (Regular Attendance)"
                    }
                } else if (summary.isBonusCancelledDueToAbsent && summary.isBonusCancelledDueToLeave) {
                    if (isBn) "হাজিরা বোনাস (অনুপস্থিতি ও সাময়িক ছুটির কারণে বাতিল)" else "Attendance Bonus (Cancelled for Absent & Leave Limit)"
                } else if (summary.isBonusCancelledDueToLeave) {
                    if (isBn) "হাজিরা বোনাস (${summary.leaveDays} দিন সাময়িক ছুটির কারণে বাতিল)" else "Attendance Bonus (Cancelled for ${summary.leaveDays} leave days)"
                } else if (summary.isBonusCancelledDueToAbsent) {
                    if (isBn) "হাজিরা বোনাস (${summary.absentDays} দিন অনুপস্থিতির জন্য বাতিল)" else "Attendance Bonus (Cancelled for ${summary.absentDays} absent days)"
                } else {
                    if (isBn) "হাজিরা বোনাস" else "Attendance Bonus"
                }
                drawPdfRow(attendanceLabel, summary.attendanceBonus)

                y += 6f
                paint.color = Color.rgb(226, 232, 240)
                canvas.drawLine(44f, y, pageWidth - 44f, y, paint)
                y += 20f

                // Section: Overtime & Extra
                ensureSpace(45f)
                paint.color = Color.rgb(5, 150, 105)
                paint.textSize = 13f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                drawShapedText(
                    canvas,
                    if (isBn) "অতিরিক্ত আয়:" else "Overtime & Extra Earnings:",
                    44f,
                    y,
                    pageWidth - 88f
                )
                y += 20f

                drawPdfRow(
                    if (isBn) "ওভারটাইম আয় (${String.format(java.util.Locale.US, "%.1f", summary.totalOtHours)} ঘণ্টা @ Tk ${String.format(java.util.Locale.US, "%.2f", summary.hourlyOtRate)}/ঘণ্টা)"
                    else "Overtime Income (${String.format(java.util.Locale.US, "%.1f", summary.totalOtHours)} hrs @ Tk ${String.format(java.util.Locale.US, "%.2f", summary.hourlyOtRate)}/hr)",
                    summary.totalOtAmount,
                    isBold = true
                )
                if (summary.nightBillTotal > 0) {
                    val nightRate = if (summary.effectiveNightRate > 0.0) summary.effectiveNightRate else profile.nightBillRate
                    drawPdfRow(
                        if (isBn) "নাইট বিল (${summary.nightBillCount}টি @ Tk ${String.format(java.util.Locale.US, "%.0f", nightRate)})"
                        else "Night Bill (${summary.nightBillCount} nights @ Tk ${String.format(java.util.Locale.US, "%.0f", nightRate)})",
                        summary.nightBillTotal
                    )
                }
                if (summary.tiffinBillTotal > 0) {
                    val tiffinRate = if (summary.effectiveTiffinRate > 0.0) summary.effectiveTiffinRate else profile.tiffinBillRate
                    drawPdfRow(
                        if (isBn) "টিফিন বিল (${summary.tiffinBillCount}টি @ Tk ${String.format(java.util.Locale.US, "%.0f", tiffinRate)})"
                        else "Tiffin Bill (${summary.tiffinBillCount} days @ Tk ${String.format(java.util.Locale.US, "%.0f", tiffinRate)})",
                        summary.tiffinBillTotal
                    )
                }
                drawPdfRow(if (isBn) "পিস রেট আয়" else "Piece Rate Earnings", summary.totalPieceAmount, isBold = summary.totalPieceAmount > 0)

                // Section: Deductions
                val hasDeductions = summary.absentDeduction > 0 || summary.advanceDeduction > 0 || summary.aponBazarDeduction > 0
                if (hasDeductions) {
                    ensureSpace(50f)
                    y += 6f
                    paint.color = Color.rgb(226, 232, 240)
                    canvas.drawLine(44f, y, pageWidth - 44f, y, paint)
                    y += 20f

                    paint.color = Color.rgb(220, 38, 38)
                    paint.textSize = 13f
                    paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                    drawShapedText(canvas, if (isBn) "কর্তন:" else "Deductions:", 44f, y, pageWidth - 88f)
                    y += 20f

                    if (summary.absentDeduction > 0) {
                        drawPdfRow(
                            if (isBn) "অনুপস্থিতি কর্তন (${summary.absentDays} দিন @ Tk ${String.format(java.util.Locale.US, "%.2f", summary.dailyAbsentRate)}/দিন)"
                            else "Absent Deduction (${summary.absentDays} days @ Tk ${String.format(java.util.Locale.US, "%.2f", summary.dailyAbsentRate)}/day)",
                            summary.absentDeduction,
                            isDeduction = true
                        )
                    }
                    if (summary.advanceDeduction > 0) {
                        drawPdfRow(if (isBn) "অগ্রিম কর্তন" else "Advance Deduction", summary.advanceDeduction, isDeduction = true)
                    }
                    if (summary.aponBazarDeduction > 0) {
                        drawPdfRow(if (isBn) "আপন বাজার কর্তন" else "Apon Bazar Deduction", summary.aponBazarDeduction, isDeduction = true)
                    }
                }

                y += 10f
                ensureSpace(140f)

                // Net Payable Box
                paint.color = Color.rgb(236, 253, 245)
                canvas.drawRect(44f, y, pageWidth - 44f, y + 46f, paint)
                paint.color = Color.rgb(5, 150, 105)
                paint.strokeWidth = 1.5f
                paint.style = Paint.Style.STROKE
                canvas.drawRect(44f, y, pageWidth - 44f, y + 46f, paint)
                paint.style = Paint.Style.FILL

                paint.color = Color.rgb(5, 150, 105)
                paint.textSize = 14f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                drawShapedText(canvas, if (isBn) "মোট প্রদেয় বেতন:" else "Net Payable Salary:", 56f, y + 28f, 260f)

                paint.textSize = 16f
                val netStr = String.format(java.util.Locale.US, "Tk %.2f", summary.totalEstimatedEarnings)
                drawShapedText(
                    c = canvas,
                    text = netStr,
                    x = pageWidth - 56f,
                    baselineY = y + 28f,
                    maxWidth = 220f,
                    align = Layout.Alignment.ALIGN_OPPOSITE
                )

                y += 70f

                // Signatures area
                paint.color = Color.rgb(100, 116, 139)
                paint.textSize = 10f
                paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                paint.strokeWidth = 1f
                canvas.drawLine(56f, y + 40f, 196f, y + 40f, paint)
                drawShapedText(
                    c = canvas,
                    text = if (isBn) "শ্রমিকের স্বাক্ষর" else "Worker's Signature",
                    x = 126f,
                    baselineY = y + 54f,
                    maxWidth = 160f,
                    align = Layout.Alignment.ALIGN_CENTER
                )

                canvas.drawLine(pageWidth - 204f, y + 40f, pageWidth - 48f, y + 40f, paint)
                drawShapedText(
                    c = canvas,
                    text = if (isBn) "অ্যাকাউন্টস / কারখানা কর্তৃপক্ষ" else "Accounts / Factory Authority",
                    x = pageWidth - 126f,
                    baselineY = y + 54f,
                    maxWidth = 180f,
                    align = Layout.Alignment.ALIGN_CENTER
                )

                // Footer note
                drawFooter(canvas)

                pdfDocument.finishPage(page)

                // Save to Phone Downloads off the Main Thread
                val cleanWorkerId = if (displayWorkerId.isNotBlank()) displayWorkerId.replace("/", "_").replace("\\", "_") else "Worker"
                fileName = "Salary_Slip_${cleanWorkerId}_${selectedMonth}.pdf"

                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                    val contentValues = ContentValues().apply {
                        put(MediaStore.MediaColumns.DISPLAY_NAME, fileName)
                        put(MediaStore.MediaColumns.MIME_TYPE, "application/pdf")
                        put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS)
                    }
                    val uri = context.contentResolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, contentValues)
                    if (uri != null) {
                        context.contentResolver.openOutputStream(uri)?.use { outStream ->
                            pdfDocument.writeTo(outStream)
                        }
                        savedUri = uri
                    }
                } else {
                    val targetDir = context.getExternalFilesDir(Environment.DIRECTORY_DOWNLOADS) ?: context.filesDir
                    if (!targetDir.exists()) targetDir.mkdirs()
                    val file = File(targetDir, fileName)
                    FileOutputStream(file).use { outStream ->
                        pdfDocument.writeTo(outStream)
                    }
                    savedUri = androidx.core.content.FileProvider.getUriForFile(
                        context,
                        "${context.packageName}.fileprovider",
                        file
                    )
                }
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.w("PdfSlipGenerator", "Failed to generate/save PDF: ${e.message}", e)
                errorMessage = e.localizedMessage ?: "Unknown error"
            } finally {
                pdfDocument.close()
            }
        }

        withContext(Dispatchers.Main) {
            if (errorMessage != null) {
                Toast.makeText(
                    context,
                    if (isBn) "পিডিএফ সংরক্ষণে সমস্যা: $errorMessage" else "Failed to save PDF: $errorMessage",
                    Toast.LENGTH_SHORT
                ).show()
            } else if (savedUri != null) {
                Toast.makeText(
                    context,
                    if (isBn) "পিডিএফ ডাউনলোড হয়েছে: $fileName" else "PDF downloaded: $fileName",
                    Toast.LENGTH_LONG
                ).show()

                val openIntent = Intent(Intent.ACTION_VIEW).apply {
                    setDataAndType(savedUri, "application/pdf")
                    addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_ACTIVITY_NEW_TASK)
                }
                val chooser = Intent.createChooser(openIntent, if (isBn) "PDF ওপেন করুন" else "Open PDF").apply {
                    addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                }
                try {
                    context.startActivity(chooser)
                } catch (_: Exception) {
                    Toast.makeText(
                        context,
                        if (isBn) "PDF খোলার জন্য কোনো অ্যাপ পাওয়া যায়নি" else "No PDF viewer app found",
                        Toast.LENGTH_SHORT
                    ).show()
                }
            }
        }

        return savedUri
    }

    private fun formatDisplayGrade(grade: String, isBn: Boolean): String {
        val clean = grade.trim()
        if (clean.isBlank()) return ""
        val lower = clean.lowercase()
        val hasGradeWord = lower.contains("grade") || clean.contains("গ্রেড")
        return if (hasGradeWord) {
            if (isBn) clean.replace("Grade", "গ্রেড", ignoreCase = true)
            else clean.replace("গ্রেড", "Grade")
        } else {
            if (isBn) "গ্রেড $clean" else "Grade $clean"
        }
    }
